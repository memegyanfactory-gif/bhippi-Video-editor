// Copies WatchFIWN's caption renderer into Bhippi, so captions draw with FIWN's own code in the
// preview and the export (docs/FIWN-CAPTIONS-PLAN.md).
//
// READ-ONLY with respect to FIWN: it reads the editor's caption modules from the FIWN checkout
// and writes `src/lib/fiwn/vendor/` inside Bhippi. Nothing in FIWN is touched.
//
//   node scripts/sync-fiwn-captions.mjs [path-to-FIWN]      (default D:/FIWN)
//
// The dynamic engine and the animation core are copied as they are (their cache-busting import
// queries removed). The flat renderer is FIWN's `drawSubtitle`, cut out of engine.js with its
// two ties to FIWN's editor state removed; each cut checks the text it expects, so a change in
// FIWN stops this script rather than quietly producing a different renderer. The style presets
// are cut out of subtitles.js as plain data. No FIWN code runs here.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fiwn = resolve(process.argv[2] ?? 'D:/FIWN');
const from = join(fiwn, 'public/editor-app/js/editor');
const to = join(here, '../src/lib/fiwn/vendor');
mkdirSync(to, { recursive: true });

const read = (name) => readFileSync(join(from, name), 'utf8');
const HEADER = (source) => `// Generated by scripts/sync-fiwn-captions.mjs from WatchFIWN (${source}). Do not edit here:\n// change it in FIWN and run the script again.\n/* eslint-disable */\n// @ts-nocheck\n`;
/** Import specifiers without FIWN's `?v=…` cache busting (Vite resolves the plain file). */
const plainImports = (code) => code.replace(/(from\s+'\.\/[^'?]+)\?v=[^']*'/g, "$1'");
const write = (name, source, code) => {
  writeFileSync(join(to, name), HEADER(source) + code.replace(/\r\n/g, '\n'));
  console.log(`wrote vendor/${name}`);
};
/** Replaces `find` exactly once, or stops: FIWN changed and this cut needs looking at. */
const cut = (code, find, replace, what) => {
  const count = code.split(find).length - 1;
  if (count !== 1) throw new Error(`sync-fiwn-captions: expected one "${what}" in FIWN, found ${count}. FIWN changed; update this script.`);
  return code.replace(find, replace);
};
/** The text of `export function name(` … up to the next top-level `}` line. */
function functionText(code, signature) {
  const start = code.indexOf(signature);
  if (start < 0) throw new Error(`sync-fiwn-captions: "${signature}" not found in FIWN`);
  const end = code.indexOf('\n}\n', start);
  return code.slice(start, end + 3);
}
function objectLiteral(code, name) {
  const start = code.indexOf(`export const ${name} = {`);
  if (start < 0) throw new Error(`sync-fiwn-captions: ${name} not found in FIWN subtitles.js`);
  const open = code.indexOf('{', start);
  let depth = 0;
  let quote = null;
  for (let i = open; i < code.length; i++) {
    const ch = code[i];
    if (quote) {
      if (ch === '\\') i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') quote = ch;
    else if (ch === '{') depth++;
    else if (ch === '}' && --depth === 0) return code.slice(open, i + 1);
  }
  throw new Error(`sync-fiwn-captions: ${name} is not closed`);
}

// 1. Copied as they are: the dynamic engine, its kits and presets, and the animation core.
for (const name of ['dynamic-captions.js', 'dynamic-presets-2.js', 'caption-layout-kit.js', 'caption-motion-kit.js', 'flying-type-caption.js', 'motion.js']) {
  write(name, name, plainImports(read(name)));
}

// 2. utils.js: only what the renderer uses (FIWN's utils also carries toasts and DOM helpers).
const utils = read('utils.js');
write('utils.js', 'utils.js: clamp, wrapText', `${cut(utils, 'export const clamp = (v, min, max) => Math.max(min, Math.min(max, v));', 'export const clamp = (v, min, max) => Math.max(min, Math.min(max, v));', 'clamp').match(/export const clamp = [^\n]*\n/)[0]}\n${functionText(utils, 'export function wrapText(')}`);

// 3. The flat renderer: drawSubtitle from engine.js, without FIWN's editor state.
let draw = functionText(read('engine.js'), 'export function drawSubtitle(');
draw = cut(draw, 'const st = styleOverride || rotatedCaptionStyle(cue, state.subtitleStyle) || state.subtitleStyle;', 'const st = styleOverride;', 'style from editor state');
draw = cut(draw, `  if (isTemplateCaptionStyle(st)) {
    const box = drawTemplateCaption(ctx, cue, srcT, W, H, st);
    if (box) {
      if (!styleOverride) state._subRect = box;
      return;
    }
  }
`, '', 'motion-text template branch');
draw = cut(draw, 'if (!styleOverride && box) state._subRect = box;\n    return;', 'return box;', 'dynamic layout hit box');
draw = cut(draw, '  if (!styleOverride) {\n    if (card) {\n      state._subRect =', '  if (false) {\n    if (card) {\n      void', 'card hit box');
draw = cut(draw, '    } else {\n      const maxLineW = lines.reduce((m, line) => Math.max(m, ctx.measureText(line).width), 0);\n      state._subRect = {', '    } else {\n      const maxLineW = lines.reduce((m, line) => Math.max(m, ctx.measureText(line).width), 0);\n      void {', 'line hit box');
if (draw.includes('state.')) throw new Error('sync-fiwn-captions: drawSubtitle still reads FIWN editor state; update this script.');
write('subtitle.js', 'engine.js drawSubtitle', `import { clamp, wrapText } from './utils.js';
import { roundRect, evalPreset, ease, IN_PRESETS, unitOffsets, EASINGS } from './motion.js';
import { drawDynamicCaption, isDynamicLayout, canonicalLayoutId, DYNAMIC_LAYOUTS, DYNAMIC_SAMPLES, sampleCueForStyle } from './dynamic-captions.js';

export { isDynamicLayout, canonicalLayoutId, DYNAMIC_LAYOUTS, DYNAMIC_SAMPLES, sampleCueForStyle, EASINGS, IN_PRESETS };

${draw}`);

// 4. The style presets, as data.
const subtitles = read('subtitles.js');
write('presets.js', 'subtitles.js: NO_ANIM, BASE_STYLE, STYLE_PRESETS', `export const NO_ANIM = ${objectLiteral(subtitles, 'NO_ANIM')};

export const BASE_STYLE = ${objectLiteral(subtitles, 'BASE_STYLE')};

export const STYLE_PRESETS = ${objectLiteral(subtitles, 'STYLE_PRESETS')};
`);
// 5. The motion-text caption templates (FIWN's Motion text library): drawn by FIWN's general layer
// engine (engine.js drawLayer), which is tied to its editor. Bundled from their entry points with
// the editor's state, colour grade and globe data stubbed out, sharing the motion core and the
// dynamic engine copied above rather than carrying second copies. Tree-shaken to what they reach.
const aspects = read('state.js').match(/export const ASPECTS = \{[\s\S]*?\n\};/);
if (!aspects) throw new Error('sync-fiwn-captions: ASPECTS not found in FIWN state.js');
const STUBS = {
  'state.js': `${aspects[0]}
export const state = { subtitleStyle: null, grade: null, assets: [], elements: [] };
export const getActiveCues = () => [];
export const on = () => () => undefined;
export const emit = () => undefined;
export const outputDuration = () => 0;
export const srcFromOut = (t) => t;
export const segmentAtOut = () => null;
export const canvasSize = () => ({ w: 1920, h: 1080 });
export const autoZoomCropRect = () => null;
export const containRect = (sw, sh, dw, dh) => { const k = Math.min(dw / sw, dh / sh); return { x: (dw - sw * k) / 2, y: (dh - sh * k) / 2, w: sw * k, h: sh * k }; };`,
  'colorgrade.js': 'export const gradedSource = (source) => source;',
  'geo.js': 'export const getLandDots = () => []; export const findCountryCentroid = () => null; export const projectPoint = () => ({ x: 0, y: 0, visible: false });',
};
const SHARED = new Set(['motion.js', 'dynamic-captions.js']);
const bundled = await build({
  stdin: {
    contents: "export { drawTemplateCaption, isTemplateCaptionStyle, templateCaptionIds } from './caption-templates.js';\nexport { buildFiwnTextCatalog, getFiwnTextTemplate } from './fiwn-text-catalog.js';",
    resolveDir: from,
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  write: false,
  treeShaking: true,
  logLevel: 'error',
  plugins: [{
    name: 'fiwn-editor-stubs',
    setup(b) {
      b.onResolve({ filter: /^\.\// }, (args) => {
        const file = args.path.replace(/\?.*$/, '').slice(2);
        if (STUBS[file]) return { path: file, namespace: 'fiwn-stub' };
        if (SHARED.has(file)) return { path: `./${file}`, external: true };
        return { path: join(args.resolveDir, file) };
      });
      b.onLoad({ filter: /.*/, namespace: 'fiwn-stub' }, (args) => ({ contents: STUBS[args.path], loader: 'js' }));
    },
  }],
});
write('templates.js', 'caption-templates.js + fiwn-text-catalog.js + engine.js drawLayer, bundled', bundled.outputFiles[0].text);

console.log(`Synced WatchFIWN captions from ${from}`);
