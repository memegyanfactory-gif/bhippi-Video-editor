const BITS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split('|').map((row) => [...row].map((c) => c === '#'))]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Advance per character, including the one-pixel gap. */
export const ADVANCE = GLYPH_W + 1;

export const textWidth = (text: string) => Math.max(0, text.length * ADVANCE - 1);

/**
 * Calls `plot` for every lit pixel of `text` drawn at (x, y). `jitter` shakes each letter up or
 * down (a laugh, a shout) — it receives the letter index and returns a row offset.
 */
export function drawText(text: string, x: number, y: number, plot: (px: number, py: number) => void, jitter?: (index: number) => number) {
  [...text.toUpperCase()].forEach((ch, index) => {
    const glyph = BITS[ch];
    if (!glyph) return;
    const dy = jitter ? jitter(index) : 0;
    glyph.forEach((row, gy) => row.forEach((on, gx) => { if (on) plot(x + index * ADVANCE + gx, y + gy + dy); }));
  });
}

/** Word-wraps to lines of at most `max` characters. */
export function wrap(text: string, max: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (!line) line = word;
    else if (line.length + 1 + word.length <= max) line += ` ${word}`;
    else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : [''];
}
